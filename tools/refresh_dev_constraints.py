"""Regenerate tools/dev-constraints.txt from the ranges in pyproject.toml.

Usage (needs network access to the package index; run it by hand, never in CI)::

    python tools/refresh_dev_constraints.py            # print the new file
    python tools/refresh_dev_constraints.py --write    # replace tools/dev-constraints.txt

For every CI platform and Python version it asks pip to resolve the ``dev``
extra, ``[build-system] requires`` and pip itself, binary wheels only, without
installing anything (``pip install --dry-run --report``). The pins are the
newest versions inside the ``pyproject.toml`` ranges that resolve on every
combination. It fails if two combinations resolve a package to different
versions; narrow the range in ``pyproject.toml`` and run it again.

pip evaluates environment markers (for example ``sys_platform == "win32"``)
for the interpreter that runs this script, not for the target platform. A
platform-only dependency of another OS can therefore be missing from the
result. ``python tools/check_dev_constraints.py --installed`` in every CI job
catches that: add the reported pin by hand. See docs/release-checklist.md,
section "Development tool constraints".
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGET = REPO_ROOT / "tools" / "dev-constraints.txt"
# The CI matrix in .github/workflows/tests.yml.
PLATFORMS = {
    "linux": ["manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "linux_x86_64"],
    "macos": ["macosx_14_0_arm64"],
    "windows": ["win_amd64"],
}
PYTHON_VERSIONS = ("3.12", "3.13")

HEADER = """\
# Exact development and build tool versions for CI and local development.
# Generated by tools/refresh_dev_constraints.py from the ranges in pyproject.toml.
# Do not edit by hand except to add a platform-only pin that
# tools/check_dev_constraints.py --installed reports. Runtime dependencies: none.
#
#   python -m pip install -c tools/dev-constraints.txt pip
#   python -m pip install -c tools/dev-constraints.txt -e ".[dev]"
"""


def requirements() -> list[str]:
    data = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    reqs = ["pip", *data["build-system"]["requires"], *data["project"]["optional-dependencies"]["dev"]]
    return list(dict.fromkeys(reqs))


def resolve(reqs: list[str], platforms: list[str], python: str) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        report_path = Path(tmp) / "report.json"
        command = [sys.executable, "-m", "pip", "install", "--dry-run", "--quiet", "--ignore-installed", "--only-binary=:all:"]
        command += ["--python-version", python, "--implementation", "cp", "--target", str(Path(tmp) / "target"), "--report", str(report_path)]
        for platform in platforms:
            command += ["--platform", platform]
        subprocess.run([*command, *reqs], check=True)
        report = json.loads(report_path.read_text(encoding="utf-8"))
    return {item["metadata"]["name"]: item["metadata"]["version"] for item in report["install"]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--write", action="store_true", help=f"replace {TARGET.relative_to(REPO_ROOT).as_posix()}")
    args = parser.parse_args(argv)
    reqs = requirements()
    merged: dict[str, tuple[str, str]] = {}
    conflicts: list[str] = []
    for os_name, platforms in PLATFORMS.items():
        for python in PYTHON_VERSIONS:
            for name, version in resolve(reqs, platforms, python).items():
                key = name.lower().replace("_", "-").replace(".", "-")
                where = f"{os_name}/{python}"
                if key in merged and merged[key][1] != version:
                    conflicts.append(f"{name}: {merged[key][1]} vs {version} on {where}")
                merged.setdefault(key, (name, version))
    if conflicts:
        print("\n".join(conflicts), file=sys.stderr)
        return 1
    text = HEADER + "".join(f"{name}=={version}\n" for _, (name, version) in sorted(merged.items()))
    if args.write:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
